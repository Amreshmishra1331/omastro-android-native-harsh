    /** Active-language string for [key]. Falls back to English. */
    fun t(key: String): String {
        val map = if (LangPrefs.language.value == "hi") HI else EN
        return map[key] ?: EN[key] ?: key
    }

    /**
     * Formatted variant of [t]: the string may contain printf-style
     * placeholders (%s, %d). Falls back to the unformatted string if the
     * arguments do not match the placeholders.
     */
    fun tf(key: String, vararg args: Any): String {
        val raw = t(key)
        return try {
            raw.format(*args)
        } catch (_: Exception) {
            raw
        }
    }

